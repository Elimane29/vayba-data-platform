WITH identities AS (
 SELECT COALESCE(NULLIF(RAW:user_name::VARCHAR, ''),
 REGEXP_SUBSTR(_SOURCE_FILE,'user=([^/]+)[.]json$',1,1,'e',1)) AS u,
 RAW:listened_at AS t, RAW:recording_msid AS m FROM VAYBA.BRONZE.LISTENS_RAW
), duplicates AS (
 SELECT COALESCE(SUM(n-1),0) AS n FROM
 (SELECT COUNT(*) AS n FROM identities GROUP BY u,t,m HAVING COUNT(*)>1)
)
SELECT 'LISTENS_RAW' AS TABLE_BRONZE, COUNT(*) AS LIGNES,
 COUNT(DISTINCT _SOURCE_FILE) AS FICHIERS, (SELECT n FROM duplicates) AS DOUBLONS
FROM VAYBA.BRONZE.LISTENS_RAW
UNION ALL
SELECT 'MB_ARTISTS_RAW',COUNT(*),COUNT(DISTINCT _SOURCE_FILE),COUNT(*)-COUNT(DISTINCT RAW:id)
FROM VAYBA.BRONZE.MB_ARTISTS_RAW
UNION ALL
SELECT 'WIKI_PAGEVIEWS_RAW',COUNT(*),COUNT(DISTINCT _SOURCE_FILE),COUNT(*)-COUNT(DISTINCT _SOURCE_FILE)
FROM VAYBA.BRONZE.WIKI_PAGEVIEWS_RAW;
