-- Manual loading of the frozen landing files. Same COPY semantics as run.load().
-- Use only after LIST confirms 25 ListenBrainz, 1580 MusicBrainz, 1234 Wikipedia files.
-- Execute with role VAYBA_YANIS and warehouse VAYBA_WH. Change run1 to run2 for replay.
EXECUTE IMMEDIATE $$
BEGIN
  BEGIN TRANSACTION;
  DELETE FROM VAYBA.BRONZE.LISTENS_RAW
    WHERE _SOURCE_FILE LIKE 'listenbrainz/week=2026-10-26/%';
  COPY INTO VAYBA.BRONZE.LISTENS_RAW (RAW, _SOURCE_FILE, _BATCH_ID, _LOADED_AT)
    FROM (SELECT $1, METADATA$FILENAME, 'yanis-20261103-run1', CURRENT_TIMESTAMP()
          FROM @VAYBA.BRONZE.LANDING_GCS/listenbrainz/week=2026-10-26/)
    FILE_FORMAT = (FORMAT_NAME = 'VAYBA.BRONZE.JSONL')
    ON_ERROR = ABORT_STATEMENT FORCE = TRUE;
  COPY INTO VAYBA.BRONZE.MB_ARTISTS_RAW (RAW, _SOURCE_FILE, _BATCH_ID, _LOADED_AT)
    FROM (SELECT $1, METADATA$FILENAME, 'yanis-20261103-run1', CURRENT_TIMESTAMP()
          FROM @VAYBA.BRONZE.LANDING_GCS/musicbrainz/)
    FILE_FORMAT = (FORMAT_NAME = 'VAYBA.BRONZE.JSONL')
    ON_ERROR = ABORT_STATEMENT;
  DELETE FROM VAYBA.BRONZE.WIKI_PAGEVIEWS_RAW
    WHERE _SOURCE_FILE LIKE 'wikipedia/week=2026-10-26/%';
  COPY INTO VAYBA.BRONZE.WIKI_PAGEVIEWS_RAW (RAW, _SOURCE_FILE, _BATCH_ID, _LOADED_AT)
    FROM (SELECT $1, METADATA$FILENAME, 'yanis-20261103-run1', CURRENT_TIMESTAMP()
          FROM @VAYBA.BRONZE.LANDING_GCS/wikipedia/week=2026-10-26/)
    FILE_FORMAT = (FORMAT_NAME = 'VAYBA.BRONZE.JSONL')
    ON_ERROR = ABORT_STATEMENT FORCE = TRUE;
  COMMIT;
  RETURN 'COMMITTED: yanis-20261103-run1';
EXCEPTION WHEN OTHER THEN
  ROLLBACK;
  RAISE;
END;
$$;
