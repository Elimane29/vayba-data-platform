USE ROLE SYSADMIN;
USE WAREHOUSE VAYBA_WH;
ALTER SESSION SET QUERY_TAG='vayba-hugo-evidence';
SELECT '01 Ecoutes bronze' AS CONTROLE, TO_VARCHAR(COUNT(*)) AS RESULTAT FROM VAYBA.DEV_HUGO_BRONZE.LISTENS_RAW
UNION ALL SELECT '02 Artistes bronze',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_BRONZE.MB_ARTISTS_RAW
UNION ALL SELECT '03 Ecoutes silver',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_SILVER.SILVER_LISTENS
UNION ALL SELECT '04 Ecoutes en quarantaine',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_SILVER.LISTENS_QUARANTINE
UNION ALL SELECT '05 Associations ecoute-artiste',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_SILVER.LISTEN_ARTISTS
UNION ALL SELECT '06 Morceaux recommandes',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_GOLD.PLAYLIST_HEBDO
UNION ALL SELECT '07 Utilisateurs evalues',TO_VARCHAR(USERS_EVALUATED) FROM VAYBA.DEV_HUGO_GOLD.METRICS_HEBDO
UNION ALL SELECT '08 Semaine evaluee',TO_VARCHAR(WEEK_START,'YYYY-MM-DD') FROM VAYBA.DEV_HUGO_GOLD.METRICS_HEBDO
UNION ALL SELECT '09 Hit rate recommandations',TO_VARCHAR(HIT_RATE_S1) FROM VAYBA.DEV_HUGO_GOLD.METRICS_HEBDO
UNION ALL SELECT '10 Hit rate popularite',TO_VARCHAR(HIT_RATE_BASELINE_S1) FROM VAYBA.DEV_HUGO_GOLD.METRICS_HEBDO
UNION ALL SELECT '11 Erreurs controles qualite',TO_VARCHAR(SUM(FAILURES)) FROM VAYBA.DEV_HUGO_OPS.QUALITY_RESULTS
UNION ALL SELECT '12 Differences apres rejeu',TO_VARCHAR(SUM(FAILURES)) FROM VAYBA.DEV_HUGO_OPS.REPLAY_RESULTS
UNION ALL SELECT '13 Champs obligatoires invalides',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_GOLD.PLAYLIST_HEBDO WHERE RECORDING_MBID IS NULL OR ARTIST_NAME IS NULL OR USER_KEY IS NULL
UNION ALL SELECT '14 Ecoutes construction',TO_VARCHAR(COUNT(DISTINCT LISTEN_KEY)) FROM VAYBA.DEV_HUGO_SILVER.TRAIN_LISTENS
UNION ALL SELECT '15 Ecoutes validation',TO_VARCHAR(COUNT(*)) FROM VAYBA.DEV_HUGO_SILVER.SILVER_LISTENS WHERE LISTENED_AT >= '2026-10-26'::TIMESTAMP_NTZ AND LISTENED_AT < '2026-11-02'::TIMESTAMP_NTZ
ORDER BY CONTROLE;
